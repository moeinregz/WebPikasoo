function detect(text: string) {
  const t = normalize(text);
  const topics = (Object.keys(TOPIC_WORDS) as Topic[]).filter((k) => has(t, TOPIC_WORDS[k]));
  let services = (Object.keys(SERVICE_WORDS) as Service[]).filter((k) => has(t, SERVICE_WORDS[k]));
  const sites = SITE_TYPES.filter((s) => has(t, s.words));
  // The generic "website" service only when nothing more specific covers it:
  // not for "سایت وردپرسی"/"سایت اختصاصی", not for "سئو سایت" (only an
  // explicit "طراحی/ساخت سایت" keeps it next to SEO, Instagram or software),
  // and not when a site type (فروشگاهی، شرکتی...) already says which site.
  if (services.includes("website")) {
    const explicit = has(t, WEBSITE_EXPLICIT);
    if (services.some((s) => s === "wordpress" || s === "custom") || sites.length || (services.length > 1 && !explicit)) {
      services = services.filter((s) => s !== "website");
    }
  }
  return { t, topics, services, sites };
}

/** Topic signature for a message — used to vary repeated answers. */
export function signature(text: string): string {
  const d = detect(text);
  return [...d.topics, ...d.services, ...d.sites.map((s) => s.key)].sort().join(",");
}

/** Builds the keyword reply for `message`, or null when nothing matched.
 *  `previousUser` is the visitor's earlier messages (oldest first). */
export function intentReply(message: string, previousUser: string[]): IntentReply | null {
  const d = detect(message);
  const sig = [...d.topics, ...d.services, ...d.sites.map((s) => s.key)].sort().join(",");
  if (!sig) return null;

  // How often this exact topic mix came up before -> which wording to use.
  const seen = previousUser.filter((m) => signature(m) === sig).length;
  const exactRepeat = previousUser.some((m) => normalize(m) === d.t);
  const n = seen;

  const parts: string[] = [];
  const actions: ChatAction[] = [];
  const has_ = (x: Topic) => d.topics.includes(x);

  if (has_("greet")) parts.push(pick(GREET, n));
  if (has_("howareyou")) parts.push(pick(HOW, n));
  if (has_("thanks")) parts.push(pick(THANKS, n));

  const businessAsked = has_("price") || d.services.length > 0 || d.sites.length > 0 || has_("support") || has_("time") || has_("contact") || has_("portfolio") || has_("order") || has_("human");

  if (has_("price")) {
    if (d.services.length || d.sites.length) {
      for (const s of d.services) {
        const p = PRICES[s];
        parts.push(`قیمت ${p.title}:\n${p.lines.map((l) => `- ${l}`).join("\n")}\n\n[${p.linkLabel}](${p.link})`);
      }
      for (const s of d.sites) {
        // A platform named next to the site type (e.g. "فروشگاهی وردپرسی") already lists its plans.
        if (d.services.some((x) => x === "wordpress" || x === "custom")) continue;
        parts.push(`قیمت ${s.name}: ${s.plan}\n\n[بیشتر بخونید](${s.link})`);
      }
    } else {
      parts.push(
        `${pick(PRICE_GENERAL, n)}\n- طراحی سایت وردپرسی: از ۲۵ میلیون تومان\n- سایت فروشگاهی: از ۴۷ میلیون تومان\n- سایت با کدنویسی اختصاصی: از ۵۸ میلیون تومان\n- نرم‌افزار و پنل مدیریت: از ۸۲ میلیون تومان\n- سئو: از ۱۵ میلیون تومان در ماه\n- ادمینی اینستاگرام: از ۱۵ میلیون تومان در ماه\n\n[جدول کامل قیمت‌ها](/website-price)`
      );
      actions.push({ label: "قیمت طراحی سایت", kind: "send", value: "قیمت طراحی سایت" }, { label: "قیمت سئو", kind: "send", value: "قیمت سئو" }, { label: "قیمت ادمین اینستاگرام", kind: "send", value: "قیمت ادمین اینستاگرام" });
    }
    parts.push(pick(PRICE_NOTE, n));
  } else {
    for (const s of d.sites) parts.push(`${s.name}: ${s.info}\n\nقیمت تقریبی: ${s.plan} [بیشتر بخونید](${s.link})`);
    for (const s of d.services) {
      if (d.sites.length && s === "website") continue;
      parts.push(`${pick(SERVICE_INFO[s], n)}\n\nقیمت: ${PRICES[s].lines[0].replace(/^[^:]+: /, "")} [${PRICES[s].linkLabel}](${PRICES[s].link})`);
    }
    if (d.services.length || d.sites.length) actions.push({ label: "قیمت دقیق‌تر می‌خوام", kind: "send", value: `قیمت ${d.sites[0]?.name ?? PRICES[d.services[0]].title}` });
  }

  if (has_("support")) parts.push(pick(SUPPORT, n));
  if (has_("time")) parts.push(pick(TIME, n));
  if (has_("contact")) parts.push(pick(CONTACT, n));
  if (has_("portfolio")) parts.push(pick(PORTFOLIO, n));
  if (has_("order") && !has_("price")) parts.push(pick(ORDER, n));
  if (has_("bye")) parts.push(pick(BYE, n));

  if (has_("human")) {
    parts.push(pick(HUMAN, n));
    actions.unshift({ label: "صحبت با کارشناس", kind: "handoff" });
  } else if (businessAsked) {
    actions.push({ label: "صحبت با کارشناس", kind: "handoff" });
  } else if (!has_("bye") && !has_("thanks")) {
    // Only small talk: invite a real question.
    parts.push(pick(HELP, n));
    actions.push({ label: "قیمت طراحی سایت", kind: "send", value: "قیمت طراحی سایت چقدره؟" }, { label: "خدمات سئو", kind: "send", value: "سئو چیه؟" });
  }

  let text = parts.join("\n\n");
  if (exactRepeat && businessAsked) text = pick(REPEAT_PREFIX, n) + text;
  const seenActions = new Set<string>();
  return {
    text,
    actions: actions.filter((a) => (seenActions.has(a.label) ? false : (seenActions.add(a.label), true))).slice(0, 4),
    topics: sig.split(","),
  };
}

