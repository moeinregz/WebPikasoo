// ---------------------------------------------------------------- normalize

const FA = "۰۱۲۳۴۵۶۷۸۹";
const AR = "٠١٢٣٤٥٦٧٨٩";

export function normalize(input: string): string {
  return (
    " " +
    input
      .toLowerCase()
      .replace(/[ي]/g, "ی")
      .replace(/[ك]/g, "ک")
      .replace(/[ۀة]/g, "ه")
      .replace(/[أإآ]/g, "ا")
      .replace(/[ؤ]/g, "و")
      .replace(/[۰-۹]/g, (d) => String(FA.indexOf(d)))
      .replace(/[٠-٩]/g, (d) => String(AR.indexOf(d)))
      .replace(/[ً-ٰٟ]/g, "") // harakat
      .replace(/[‌‍‎‏]/g, " ") // ZWNJ & marks
      .replace(/[.,!?؟،؛;:()"'«»\-_/\\*#@[\]{}|<>+=~`^]/g, " ")
      .replace(/(.)\1{2,}/g, "$1$1") // "سلاااام" -> "سلاام"
      .replace(/\s+/g, " ")
      .trim() +
    " "
  );
}

/** True when any keyword occurs; `^`/`$` in a keyword mean a word edge. */
function has(text: string, words: string[]): boolean {
  return words.some((w) => text.includes(w.replace(/\^/g, " ").replace(/\$/g, " ")));
}

