/** The menu a site starts from: the template's own default, else the trade's starter. */
export function defaultMenuFor(templateId?: string | null, tradeId?: string | null): MenuCategory[] {
  return (templateId && DEFAULT_MENUS[templateId]) || (tradeId && STARTER_MENUS[tradeId]) || [];
}
